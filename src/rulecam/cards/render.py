"""Render rule cards and declined cards to HTML (Jinja2) and PNG (Playwright), 1080 x 1350.

Templates autoescape every value: plan text (back-translations, standards, decline reasons) is
model or owner text and never markup. The only unescaped content is generated here: the QR
code's SVG (built by `qrcode` from the worker URL) and the skeleton render's `data:` URI.
"""

from __future__ import annotations

import base64
from pathlib import Path
from typing import Final

import jinja2
import qrcode
import qrcode.image.svg
from markupsafe import Markup

from rulecam.cards.errors import CardError
from rulecam.cards.models import DeclinedCardData, RuleCardData
from rulecam.cards.templates import DECLINED_CARD_TEMPLATE, RULE_CARD_TEMPLATE
from rulecam.log import get_logger

_log = get_logger(__name__)

CARD_WIDTH: Final = 1080
CARD_HEIGHT: Final = 1350
PNG_MAGIC: Final = b"\x89PNG\r\n\x1a\n"
VERDICT_CLASS: Final = {
    "observable": "green",
    "caveat": "amber",
    "not_observable": "red",
    "declined": "red",
}

_env = jinja2.Environment(
    autoescape=True,
    undefined=jinja2.StrictUndefined,
    trim_blocks=True,
    lstrip_blocks=True,
    keep_trailing_newline=True,
)
_rule_template = _env.from_string(RULE_CARD_TEMPLATE)
_declined_template = _env.from_string(DECLINED_CARD_TEMPLATE)


def qr_svg(url: str) -> Markup:
    """Return an inline SVG QR code for `url` (deterministic)."""
    image = qrcode.make(url, image_factory=qrcode.image.svg.SvgPathImage, border=2)
    return Markup(image.to_string(encoding="unicode"))  # noqa: S704 - generated by qrcode


def checked_by(card: RuleCardData) -> tuple[str, ...]:
    """The independent checkers that actually ran on the rule (Glimmer, Spark Open)."""
    names: tuple[str, ...] = ("Glimmer",) if card.glimmer_checked else ()
    if card.spark_open in {"findings", "no_findings"}:
        names += ("Spark Open",)
    return names


def render_rule_card_html(card: RuleCardData, *, skeleton_png: bytes | None = None) -> str:
    """Render a rule card to HTML.

    Args:
        card: The card's data (`cards.build.rule_card`).
        skeleton_png: The rule's skeleton render (P4-05) as PNG bytes, if there is one.

    Returns:
        The HTML document.

    Raises:
        CardError: If `skeleton_png` is not a PNG.
    """
    skeleton_uri = None
    if skeleton_png is not None:
        if not skeleton_png.startswith(PNG_MAGIC):
            msg = "skeleton render must be a PNG"
            raise CardError(msg)
        skeleton_uri = Markup(  # noqa: S704 - base64 alphabet only
            f"data:image/png;base64,{base64.b64encode(skeleton_png).decode('ascii')}"
        )
    return _rule_template.render(
        card=card,
        verdict_class=VERDICT_CLASS.get(card.feasibility or "", ""),
        checked_by=checked_by(card),
        qr_svg=qr_svg(card.worker_url) if card.worker_url else None,
        skeleton_uri=skeleton_uri,
    )


def render_declined_card_html(card: DeclinedCardData) -> str:
    """Render a declined card to HTML (category, reason and alternative only)."""
    return _declined_template.render(card=card)


async def render_card_png(html: str, output_path: Path) -> Path:
    """Render a card's HTML to a 1080 x 1350 PNG with headless Chromium (Playwright).

    Args:
        html: The card's HTML.
        output_path: Where to write the PNG.

    Returns:
        `output_path`.

    Raises:
        CardError: If Playwright (the `ui` extra) is not installed.
    """
    try:
        from playwright.async_api import async_playwright  # noqa: PLC0415 - optional extra
    except ImportError as exc:
        msg = "PNG cards need Playwright: uv sync --extra ui && playwright install chromium"
        raise CardError(msg) from exc
    output_path.parent.mkdir(parents=True, exist_ok=True)
    async with async_playwright() as playwright:
        browser = await playwright.chromium.launch(headless=True)
        try:
            page = await browser.new_page(viewport={"width": CARD_WIDTH, "height": CARD_HEIGHT})
            await page.set_content(html)
            await page.screenshot(path=str(output_path))
        finally:
            await browser.close()
    _log.info("card_png_rendered", path=str(output_path))
    return output_path
