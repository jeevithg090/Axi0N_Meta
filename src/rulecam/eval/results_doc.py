"""README and RESULTS sections built from measured runs (`rulecam eval results`, add-on 1.1).

Every number the README or `eval/RESULTS.md` shows must be read from a result file under
`reports/eval/` and carry its run, date and git SHA. `eval/results.yaml` lists the facts:

```yaml
sources:
  campaign:
    file: reports/eval/2026-11-01-live-test-campaign.json
    run: live test campaign, run 2
facts:
  - source: campaign
    run: T02                      # appended to the source's run id
    date: "[id=T02].started_at"   # a path to an ISO time (or `date:` on the source)
    label: Distance measured, worker to moving forklift
    path: "[id=T02].events[0].measurement.value"
    format: "{:.2f} m"
```

A path is dotted keys, `[n]` list indices and `[key=value]` list selections. `path` may be a
list, filled into `format` in order; `scale: 100` turns a share into a percentage. The git SHA
is the commit that added the result file (`git log --diff-filter=A`), or the file's own
`git_sha` field when it records the code it ran.

`render_section` writes one Markdown table; `splice` replaces the text between
`<!-- BEGIN RESULTS … -->` and `<!-- END RESULTS -->` markers, nothing else.
"""

from __future__ import annotations

import json
import re
import subprocess
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

import yaml

from rulecam.eval.errors import EvalError

BEGIN = "<!-- BEGIN RESULTS (generated by `uv run rulecam eval results`; do not edit) -->"
END = "<!-- END RESULTS -->"
COLUMNS = ("Measured", "Value", "Run", "Date", "Git SHA", "Source")
_STEP = re.compile(r"\.?([^.\[\]]+)|\[(\d+)\]|\[([^=\]]+)=([^\]]+)\]")
_NUMBER = re.compile(r"-?\d+(?:\.\d+)?")


@dataclass(frozen=True)
class Fact:
    """One number shown in the docs, resolved from its result file."""

    label: str
    value: str
    run: str
    date: str
    sha: str
    source: str


def resolve(data: object, path: str) -> object:
    """Follow a path (`a.b[0][id=T02].c`) into parsed JSON.

    Raises:
        EvalError: If a step does not exist.
    """
    node = data
    pos = 0
    while pos < len(path):
        found = _STEP.match(path, pos)
        if found is None or found.end() == pos:
            msg = f"bad path {path!r} at {pos}"
            raise EvalError(msg)
        pos = found.end()
        try:
            node = _step(node, *found.groups())
        except (KeyError, IndexError, StopIteration) as exc:
            msg = f"path {path!r} does not exist (failed at {found.group(0)!r})"
            raise EvalError(msg) from exc
    return node


def _step(
    node: object, key: str | None, index: str | None, field: str | None, wanted: str | None
) -> object:
    if key is not None and isinstance(node, Mapping):
        return node[key]
    if index is not None and isinstance(node, list):
        return node[int(index)]
    if field is not None and isinstance(node, list):
        return next(n for n in node if isinstance(n, Mapping) and str(n.get(field)) == wanted)
    raise KeyError(key or index or field)


def _load_json(path: Path) -> object:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        msg = f"cannot read result file {path}: {exc}"
        raise EvalError(msg) from exc


def git_sha(path: Path, repo: Path) -> str:
    """The short SHA of the commit that added `path` (empty when git cannot tell)."""
    try:
        out = subprocess.run(  # noqa: S603 - fixed arguments
            ["git", "log", "--diff-filter=A", "--format=%h", "-1", "--", str(path)],  # noqa: S607
            cwd=repo,
            capture_output=True,
            text=True,
            check=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    return out.stdout.strip()


def _format(spec: Mapping[str, object], data: object) -> str:
    paths = spec["path"] if isinstance(spec["path"], list) else [spec["path"]]
    scale = float(str(spec.get("scale", 1)))
    values = []
    for path in paths:
        value = resolve(data, str(path))
        if isinstance(value, bool) or not isinstance(value, int | float):
            msg = f"{spec.get('label')!r}: {path} is not a number ({value!r})"
            raise EvalError(msg)
        values.append(value * scale if scale != 1 else value)
    return str(spec.get("format", "{}")).format(*values)


def load_facts(
    facts_file: Path, repo: Path, *, sha: Callable[[Path], str] | None = None
) -> list[Fact]:
    """Resolve every fact of `facts_file` (paths relative to `repo`).

    Args:
        facts_file: `eval/results.yaml`.
        repo: The repository root.
        sha: The git SHA of a result file (default: the commit that added it).

    Raises:
        EvalError: If the facts file, a result file or a path is missing or not a number.
    """
    try:
        spec = yaml.safe_load(facts_file.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as exc:
        msg = f"cannot read {facts_file}: {exc}"
        raise EvalError(msg) from exc
    sources: Mapping[str, Mapping[str, object]] = spec.get("sources") or {}
    find_sha = sha or (lambda path: git_sha(path, repo))
    loaded: dict[str, tuple[object, str]] = {}
    out = []
    for fact in spec.get("facts") or []:
        name = str(fact["source"])
        if name not in sources:
            msg = f"fact {fact.get('label')!r} names unknown source {name!r}"
            raise EvalError(msg)
        source = sources[name]
        file = str(source["file"])
        if name not in loaded:
            data = _load_json(repo / file)
            recorded = data.get("git_sha") if isinstance(data, Mapping) else None
            loaded[name] = (data, str(recorded) if recorded else find_sha(repo / file))
        data, commit = loaded[name]
        date_path = fact.get("date") or source.get("date")
        date = str(resolve(data, str(date_path)))[:10] if date_path else ""
        run = str(source.get("run", Path(file).stem))
        out.append(
            Fact(
                label=str(fact["label"]),
                value=_format(fact, data),
                run=f"{run}: {fact['run']}" if fact.get("run") else run,
                date=date,
                sha=commit or "not committed",
                source=file,
            )
        )
    return out


def render_section(facts: Sequence[Fact], intro: str = "") -> str:
    """The generated block: an optional intro and one table, between the markers."""
    lines = [BEGIN, ""]
    if intro:
        lines += [intro, ""]
    lines += ["| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    lines += [
        f"| {f.label} | {f.value} | {f.run} | {f.date} | `{f.sha}` | [`{Path(f.source).name}`]"
        f"({f.source}) |"
        for f in facts
    ]
    return "\n".join([*lines, "", END])


def splice(text: str, section: str, *, prefix: str = "") -> str:
    """Replace the generated block in `text` (paths in `section` get `prefix`, e.g. `../`).

    Raises:
        EvalError: If the markers are missing.
    """
    start, stop = text.find(BEGIN), text.find(END)
    if start < 0 or stop < start:
        msg = "the file has no generated RESULTS markers"
        raise EvalError(msg)
    if prefix:
        section = section.replace("](reports/", f"]({prefix}reports/")
    return text[:start] + section + text[stop + len(END) :]


def section_of(text: str) -> str:
    """The generated block of a file (markers included); empty when there is none."""
    start, stop = text.find(BEGIN), text.find(END)
    return text[start : stop + len(END)] if 0 <= start < stop else ""


def table_rows(section: str) -> list[dict[str, str]]:
    """The generated table's rows as `column -> cell`."""
    rows = []
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == len(COLUMNS) and cells[0] != COLUMNS[0] and not set(cells[0]) <= {"-"}:
            rows.append(dict(zip(COLUMNS, cells, strict=True)))
    return rows


def numbers(text: str) -> list[str]:
    """Number tokens in text (`2.90`, `-1.13`, `416`)."""
    return _NUMBER.findall(text.replace(",", ""))


def numeric_leaves(data: object) -> list[float]:
    """Every number in parsed JSON."""
    if isinstance(data, bool):
        return []
    if isinstance(data, int | float):
        return [float(data)]
    if isinstance(data, Mapping):
        return [n for v in data.values() for n in numeric_leaves(v)]
    if isinstance(data, list):
        return [n for v in data for n in numeric_leaves(v)]
    return []


def in_result(token: str, leaves: Sequence[float]) -> bool:
    """Whether a shown number is some value of the file at the shown precision (or as a %)."""
    decimals = len(token.split(".", 1)[1]) if "." in token else 0
    shown = abs(float(token))
    return any(
        round(abs(leaf) * scale, decimals) == round(shown, decimals)
        for leaf in leaves
        for scale in (1.0, 100.0)
    )


def unbacked_numbers(section: str, repo: Path) -> list[str]:
    """Numbers in a generated block that are not in the result file their row cites.

    The `Value` cell of every row is checked against its `Source` file; the rest of the block
    (outside the table) must hold no number at all.
    """
    problems = []
    for line in section.splitlines():
        if line.startswith("|") or line.startswith("<!--"):
            continue
        problems += [f"number {n!r} outside the table: {line!r}" for n in numbers(line)]
    for row in table_rows(section):
        found = re.search(r"\(((?:\.\./)?reports/eval/[^)]+\.json)\)", row["Source"])
        if found is None:
            problems.append(f"{row['Measured']}: no result file cited")
            continue
        leaves = numeric_leaves(_load_json(repo / found.group(1).removeprefix("../")))
        problems += [
            f"{row['Measured']}: {n} is not in {found.group(1)}"
            for n in numbers(row["Value"])
            if not in_result(n, leaves)
        ]
    return problems
