"""Shared shape for the evaluation runners E3-E11 (task P4-07, MP §8).

Every runner answers one question, writes `eval/results/<id>.json`, and renders one table into
`eval/RESULTS.md` between its own markers. This module holds the parts they all share: the
result record, the JSON writer, the table renderer and the marker splice.

Two rules every runner follows:

* **A result that did not come from the real system is marked `simulated` and says why.** A
  simulated result can never be quoted as evidence, and the rendered table says so in bold.
* **"Not measured" is a result.** A runner with no input writes a result with no rows and a
  caveat, rather than nothing at all, so `RESULTS.md` says what was not measured instead of
  staying quiet about it.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Final

from pydantic import BaseModel, ConfigDict, Field

RESULTS_DIR: Final = Path("eval/results")
PERCENT: Final = 100.0


class ResultError(ValueError):
    """A results file is missing the markers a runner's section goes between."""


class Row(BaseModel):
    """One row of a runner's table: a named figure, with what it was measured over."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    name: str = Field(min_length=1)
    value: str = Field(min_length=1)
    detail: str = ""


class RunnerResult(BaseModel):
    """One runner's whole result.

    Attributes:
        id: The runner id, e.g. `e4`.
        title: The question the runner answers, for the table heading.
        rows: The figures. Empty means nothing could be measured.
        caveats: What the figures do not tell you, and what was missing.
        simulated: True when any figure did not come from the real system.
        simulated_because: Why, required when `simulated`.
        generated_at: When the runner ran.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    id: str = Field(pattern=r"^e[0-9]+(-[a-z]+)?$")
    title: str = Field(min_length=1)
    rows: tuple[Row, ...] = ()
    caveats: tuple[str, ...] = ()
    simulated: bool = False
    simulated_because: str = ""
    generated_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @property
    def measured(self) -> bool:
        """Whether this runner produced any figure at all."""
        return bool(self.rows)


def not_measured(runner_id: str, title: str, because: str) -> RunnerResult:
    """Build the result of a runner that had nothing to measure.

    Args:
        runner_id: The runner id.
        title: The question it answers.
        because: What was missing, in a sentence a reader can act on.

    Returns:
        A result with no rows and that reason as its only caveat.
    """
    return RunnerResult(id=runner_id, title=title, caveats=(f"Not measured: {because}",))


def percent(numerator: int, denominator: int) -> str:
    """Format a count as `62.5% (10/16)`, or `n/a (0/0)` when there is nothing to divide by."""
    if denominator == 0:
        return f"n/a ({numerator}/{denominator})"
    return f"{numerator / denominator * PERCENT:.1f}% ({numerator}/{denominator})"


def plural(count: int, noun: str) -> str:
    """`1 rule`, `3 rules`: a count with its noun, pluralised with a trailing `s`."""
    return f"{count} {noun}" if count == 1 else f"{count} {noun}s"


def begin(runner_id: str) -> str:
    """The opening marker of a runner's section."""
    return f"<!-- BEGIN {runner_id.upper()} (generated by eval/runners/{runner_id}.py) -->"


def end(runner_id: str) -> str:
    """The closing marker of a runner's section."""
    return f"<!-- END {runner_id.upper()} -->"


def render(result: RunnerResult) -> str:
    """Render a runner's section as Markdown, markers included.

    Args:
        result: The runner's result.

    Returns:
        Markdown ending in a newline.
    """
    lines = [begin(result.id), "", f"## {result.id.upper()} — {result.title}", ""]
    if result.simulated:
        lines += [
            f"> **Simulated. This is not an {result.id.upper()} result.** "
            f"{result.simulated_because}",
            "",
        ]
    if result.rows:
        lines += ["| Measure | Value | Over what |", "|---|---|---|"]
        lines += [f"| {r.name} | {r.value} | {r.detail} |" for r in result.rows]
        lines += [""]
    else:
        lines += ["No figure was produced.", ""]
    if result.caveats:
        lines += [f"- {c}" for c in result.caveats]
        lines += [""]
    lines += [end(result.id), ""]
    return "\n".join(lines)


def splice_section(text: str, runner_id: str, section: str) -> str:
    """Replace a runner's marked section in `text` with already rendered Markdown.

    Runners with their own layout (E1's tables) render the section themselves and splice it
    here, so every runner shares one set of markers and one splice.

    Args:
        text: The current results file.
        runner_id: The runner id, which names the markers.
        section: The rendered section, markers included.

    Returns:
        The updated contents.

    Raises:
        ResultError: If the markers are missing or out of order.
    """
    opening, closing = begin(runner_id), end(runner_id)
    start, stop = text.find(opening), text.find(closing)
    if start < 0 or stop < 0 or stop < start:
        msg = (
            f"the results file needs the markers {opening!r} and {closing!r}, in that order, "
            f"for the {runner_id.upper()} section to be written into"
        )
        raise ResultError(msg)
    return text[:start] + section.rstrip("\n") + text[stop + len(closing) :]


def splice(text: str, result: RunnerResult) -> str:
    """Replace a runner's marked section in `text` with its rendered table.

    Args:
        text: The current results file.
        result: The runner's result.

    Returns:
        The updated contents.

    Raises:
        ResultError: If the markers are missing or out of order.
    """
    return splice_section(text, result.id, render(result))


def write_json(result: RunnerResult, *, results_dir: Path = RESULTS_DIR) -> Path:
    """Write `eval/results/<id>.json` and return the path.

    Args:
        result: The runner's result.
        results_dir: Where results go.

    Returns:
        The path written.
    """
    results_dir.mkdir(parents=True, exist_ok=True)
    path = results_dir / f"{result.id}.json"
    path.write_text(
        json.dumps(result.model_dump(mode="json"), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return path


def write_section(result: RunnerResult, path: Path) -> Path:
    """Write a runner's section into a results file between its markers.

    Args:
        result: The runner's result.
        path: The results file, which must already hold the markers.

    Returns:
        The path written.

    Raises:
        ResultError: If the file is missing or has no markers.
    """
    if not path.is_file():
        msg = f"no results file at {path}"
        raise ResultError(msg)
    path.write_text(splice(path.read_text(encoding="utf-8"), result), encoding="utf-8")
    return path


def publish(
    results: Sequence[RunnerResult], *, results_path: Path, results_dir: Path = RESULTS_DIR
) -> tuple[Path, ...]:
    """Write every runner's JSON and splice every section into the results file.

    Args:
        results: The runners' results.
        results_path: `eval/RESULTS.md`.
        results_dir: Where the JSON files go.

    Returns:
        The JSON paths written, in order.

    Raises:
        ResultError: If the results file is missing a runner's markers. Nothing is written in
            that case, so the file never ends up half updated.
    """
    text = results_path.read_text(encoding="utf-8") if results_path.is_file() else ""
    if not text:
        msg = f"no results file at {results_path}"
        raise ResultError(msg)
    for result in results:
        text = splice(text, result)  # raises before anything is written
    written = tuple(write_json(r, results_dir=results_dir) for r in results)
    results_path.write_text(text, encoding="utf-8")
    return written
